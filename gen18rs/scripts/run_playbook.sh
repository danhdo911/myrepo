#!/bin/bash
set -e -o pipefail

# Variables
DOCKER_COMPOSE_FILE=$1
PLAYBOOK_FILE=$2
ANSIBLE_ENVIRONMENT_DEPLOYMENT=$3
ANSIBLE_ENVIRONMENT_INVENTORY=$4

ANSIBLE_PLAYBOOK_OPTS=${ANSIBLE_PLAYBOOK_OPTS:-"-v"}
DOCKER_SERVICE=${DOCKER_SERVICE:-ansible}

# Run playbook
docker-compose -f ${DOCKER_COMPOSE_FILE} run --rm \
    -e ANSIBLE_ENVIRONMENT_DEPLOYMENT=${ANSIBLE_ENVIRONMENT_DEPLOYMENT} \
    -e ANSIBLE_ENVIRONMENT_INVENTORY=${ANSIBLE_ENVIRONMENT_INVENTORY} \
    -e ANSIBLE_PLAYBOOK_OPTS=${ANSIBLE_PLAYBOOK_OPTS} \
    -e ANSIBLE_MAIN_PLAYBOOK=${PLAYBOOK_FILE} \
    ${DOCKER_SERVICE}