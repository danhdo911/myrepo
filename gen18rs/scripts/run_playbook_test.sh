#!/bin/bash
set -e -o pipefail

# Variables
DOCKER_COMPOSE_FILE=$1
PLAYBOOK_FILE=$2
ANSIBLE_INVENTORY=$3

ANSIBLE_PLAYBOOK_OPTS=${ANSIBLE_PLAYBOOK_OPTS:-"-v"}
DOCKER_SERVICE=${DOCKER_SERVICE:-ansible}

# Run playbook
docker-compose -f ${DOCKER_COMPOSE_FILE} run --rm \
    -e ANSIBLE_INVENTORY=${ANSIBLE_INVENTORY} \
    -e ANSIBLE_PLAYBOOK_OPTS=${ANSIBLE_PLAYBOOK_OPTS} \
    -e ANSIBLE_MAIN_PLAYBOOK=${PLAYBOOK_FILE} \
    ${DOCKER_SERVICE}